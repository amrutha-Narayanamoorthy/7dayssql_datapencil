-- 1. Total sales values
select sum(oi.quantity * oi.unit_price) as total_sales
from orders o join orders_item oi
 on o.order_id= oi.order_id
 where status<>'cancelled';
 
 
-- 2.revenue by product category

select p.category, sum(oi.quantity*oi.unit_price) as revenue
from orders o
join orders_item oi
on o.order_id=oi.order_id
join products p
on oi.product_id=p.product_id
where o.status<>'cancelled'
group by p.category
order by revenue asc;

use sql7challenge;

-- 3. Top 10 products by revenue
select p.product_name, sum(oi.quantity * oi.unit_price) as revenue
from products p
join orders_item oi
on oi.product_id=p.product_id
join orders o
on o.order_id=oi.order_id
where o.status<>'cancelled'
group by p.product_name
order by revenue desc
limit 10;

-- 4. Montly revenue trend - calculate revenue month by month

select sum(oi.quantity * oi.unit_price) as revenue , month(o.order_date) as months
from orders o
join orders_item oi
on o.order_id=oi.order_id
where o.status<>'cancelled'
group by months
order by  revenue asc;


--5. revenue by sales channel
-- identify which sales channel generate highest revenue
select sum(oi.quantity*oi.unit_price) as revenue, o.channel
from orders_item oi
join orders o
on o.order_id=oi.order_id
where o.status<>'cancelled'
group by o.channel
order by revenue desc;

--6. Total quantity sold by product category
--calculate the total quantity of product sold in each category
select p.category, sum(oi.quantity) as total_qty_sold
from products p 
join orders_item oi
on p.product_id=oi.product_id
join orders o
on oi.order_id=o.order_id
where o.status<>'cancelled'
group by p.category
order by total_qty_sold;


--7. payment method analysis
--count howmany payments were made using each method
select payment_method, count(*) as no_of_payments
from payments
group by payment_method
order by no_of_payments;


create table payments(
payment_id int primary key,
order_id int not null,
payment_method varchar(20),
payment_status varchar(20),
amount float not null,
foreign key (order_id) references orders(order_id));

--8. payment status analysis
count payment by their status
select  payment_status, count(*)
from payments
group by payment_status
order by count(*) desc;

--9. Average payment amount
-- calculate the average recorded payment amount
select AVG(amount)
from payments
where payment_status='Paid';

--10. Payment amount by Payment method
-- Calculate the total recorded payment amount for each payment method
select sum(amount), payment_method
from payments
where payment_status='Paid'
group by payment_method
order by sum(amount);

